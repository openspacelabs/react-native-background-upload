package ai.openspace.backgroundupload

import com.facebook.react.bridge.Arguments
import com.facebook.react.bridge.Promise
import com.facebook.react.bridge.ReactApplicationContext
import com.facebook.react.bridge.ReadableArray
import com.facebook.react.bridge.ReadableMap
import com.facebook.react.bridge.WritableArray
import com.facebook.react.bridge.WritableMap
import com.facebook.react.common.LifecycleState
import java.util.concurrent.ExecutorService
import java.util.concurrent.Executors
import java.util.concurrent.Future
import java.util.concurrent.TimeUnit

/**
 * TurboModule (New Architecture). [NativeRNFileUploaderSpec] is generated by
 * codegen from `src/NativeRNFileUploader.ts` into this same package (see
 * `codegenConfig.android.javaPackageName` in package.json).
 *
 * A thin shell over [QueueController]. Every promise method runs on one
 * single-thread executor ([queueExecutor]), because enqueue copies files and
 * every method touches the disk. The promise resolves from that executor.
 * getRequests() is synchronous and reads the in-memory index only.
 */
class UploaderModule(context: ReactApplicationContext) :
  NativeRNFileUploaderSpec(context) {

  companion object {
    const val NAME = "RNFileUploader"
    const val TAG = "RNFileUploader.UploaderModule"

    /** The longest getRequests() waits for the first-launch import. */
    private const val IMPORT_WAIT_MS = 2_000L

    // The live module, so EventReporter can reach the codegen emitters: they
    // are protected on the generated spec. Null whenever JS is absent
    // (headless worker, mid-reload); outcomes are journaled before they are
    // emitted, so a dropped live event is never lost.
    @Volatile
    var instance: UploaderModule? = null
      private set

    /** One thread for every module-side disk operation. It outlives a JS reload. */
    val queueExecutor: ExecutorService = Executors.newSingleThreadExecutor { r ->
      Thread(r, "RNFileUploader.queue")
    }
  }

  private val store = QueueStore.get(context)
  private val journal = EventJournal.get(context)
  private val settings = QueueSettingsStore.get(context)
  private val scheduler = WorkManagerScheduler(context)
  private val controller = QueueController(store, journal, settings, EventReporter, scheduler)

  // The v9 import, then the v9 work cancel, then the boot sweep.
  // getRequests() waits for the import only (file reads and row saves), so
  // the first call after an upgrade already shows the legacy rows. The
  // cancel opens the WorkManager database, so it runs after that wait.
  private val importDone: Future<Boolean>

  init {
    instance = this
    importDone = queueExecutor.submit<Boolean> {
      runCatching { LegacyImport.runOnce(context, store) }
        .onFailure { Diag.error("v9 import failed", it) }
        .getOrDefault(true) // a failed import still cancels the v9 work
    }
    queueExecutor.execute {
      if (runCatching { importDone.get() }.getOrDefault(false)) {
        runCatching { scheduler.cancelV9Work() }.onFailure { Diag.error("v9 work cancel failed", it) }
      }
      runCatching { controller.sweep() }.onFailure { Diag.error("boot sweep failed", it) }
    }
  }

  // Set by invalidate(). A drain still queued on the executor then does not
  // make this dead module the journal's listener.
  @Volatile
  private var invalidated = false

  override fun invalidate() {
    // A reload constructs the replacement before tearing this one down, so
    // only clear the pointer (and the listener) when it still refers to us.
    // The flag goes first: the drain reads it under the journal lock.
    invalidated = true
    journal.stopListening(this)
    if (instance === this) instance = null
    super.invalidate()
  }

  override fun getName(): String = NAME

  /** Picks the progress throttle interval: 1 s in the foreground, 10 min otherwise. */
  fun isForeground(): Boolean = reactApplicationContext.lifecycleState == LifecycleState.RESUMED

  // MARK: - Event emission (called by EventReporter)

  fun emitState(params: WritableMap) = safeEmit { emitOnState(params) }

  fun emitProgress(params: WritableMap) = safeEmit { emitOnProgress(params) }

  fun emitAttempt(params: WritableMap) = safeEmit { emitOnAttempt(params) }

  fun emitSettled(params: WritableMap) = safeEmit { emitOnSettled(params) }

  fun emitNotification(params: WritableMap) = safeEmit { emitOnNotification(params) }

  private inline fun safeEmit(emit: () -> Unit) {
    try {
      emit()
    } catch (exc: NullPointerException) {
      // The emitter callback exists only while the C++ TurboModule does, so a
      // null callback is expected before setup and after teardown. It is also
      // null for the whole process on the old architecture, so warn.
      Diag.warn("live event dropped (no event emitter; New Architecture required)")
    } catch (exc: Throwable) {
      Diag.error("failed to emit live event", exc)
    }
  }

  // MARK: - Promise methods

  /** Runs [block] on the queue executor and settles [promise] with its value or a coded rejection. */
  private fun onQueue(promise: Promise, block: () -> Any?) {
    queueExecutor.execute {
      try {
        promise.resolve(block())
      } catch (e: QueueException) {
        promise.reject(e.code, e.message, e)
      } catch (e: EntryParsing.InvalidEntryException) {
        promise.reject(QueueException.E_INVALID, e.message, e)
      } catch (e: Throwable) {
        Diag.error("queue operation failed", e)
        promise.reject(QueueException.E_STORAGE, e.message ?: e.javaClass.simpleName, e)
      }
    }
  }

  /**
   * Saves the notification configuration (read by headless workers) and the
   * retry defaults. Each call replaces the full configuration. lifetimeMs is
   * not stored: JS already applied it to expiresAt.
   */
  override fun configure(options: ReadableMap) {
    NotificationConfig.save(reactApplicationContext, NotificationConfig.fromReadableMap(options))
    @Suppress("UNCHECKED_CAST")
    val retry = JsonBridge.valueOf(options, "retry") as? Map<String, Any?>
    val defaults = QueueSettingsStore.retryDefaults(retry)
    queueExecutor.execute {
      runCatching { controller.configureRetry(defaults) }
        .onFailure { Diag.error("could not save the retry defaults", it) }
    }
  }

  override fun enqueue(entry: ReadableMap, promise: Promise) {
    // Parse on the calling thread: the ReadableMap belongs to the bridge call.
    val parsed = try {
      EntryParsing.parse(entry)
    } catch (e: EntryParsing.InvalidEntryException) {
      promise.reject(QueueException.E_INVALID, e.message, e)
      return
    }
    onQueue(promise) { controller.enqueue(parsed) }
  }

  // scope is { keys?: string[] }; {} is the whole queue. Null (a stale JS
  // bundle that sends no argument) is also the whole queue, not a crash.
  // Parse on the calling thread, as enqueue does.
  override fun pause(scope: ReadableMap?, promise: Promise) {
    val keys = try {
      EntryParsing.scopeKeys(scope)
    } catch (e: EntryParsing.InvalidEntryException) {
      promise.reject(QueueException.E_INVALID, e.message, e)
      return
    }
    onQueue(promise) { controller.pause(keys); null }
  }

  override fun resume(scope: ReadableMap?, promise: Promise) {
    val keys = try {
      EntryParsing.scopeKeys(scope)
    } catch (e: EntryParsing.InvalidEntryException) {
      promise.reject(QueueException.E_INVALID, e.message, e)
      return
    }
    onQueue(promise) { controller.resume(keys); null }
  }

  override fun cancel(id: String, promise: Promise) = onQueue(promise) { controller.cancel(id); null }

  override fun setWifiOnly(enabled: Boolean, promise: Promise) =
    onQueue(promise) { controller.setWifiOnly(enabled); null }

  override fun updateHeaders(patch: ReadableMap, promise: Promise) {
    val headers = try {
      EntryParsing.headerPatch(patch)
    } catch (e: EntryParsing.InvalidEntryException) {
      promise.reject(QueueException.E_INVALID, e.message, e)
      return
    }
    onQueue(promise) { controller.updateHeaders(headers); null }
  }

  /** Synchronous. From the in-memory index, never from disk. */
  override fun getRequests(): WritableArray {
    runCatching { importDone.get(IMPORT_WAIT_MS, TimeUnit.MILLISECONDS) }
    val out = Arguments.createArray()
    RequestIndex.shared.snapshot().forEach { out.pushMap(JsonBridge.toWritableMap(it.toMap())) }
    return out
  }

  /**
   * Every unacknowledged outcome, each counted as one more delivery. JS
   * subscribes to onSettled, then calls this at once, so this call makes
   * the module the journal's listener. The flip and the scan share the
   * journal lock: an outcome settled before it is in this drain (journaled
   * at 0, returned at 1); one settled after is emitted live at 1.
   */
  override fun getUnacknowledgedEvents(promise: Promise) {
    onQueue(promise) {
      val out = Arguments.createArray()
      controller.unacknowledged(this) { !invalidated }.forEach { out.pushMap(it.toWritableMap()) }
      out
    }
  }

  /** Resolves void. Idempotent; unknown ids are ignored. */
  override fun ackEvents(ids: ReadableArray, promise: Promise) {
    val eventIds = (0 until ids.size()).mapNotNull { runCatching { ids.getString(it) }.getOrNull() }
    onQueue(promise) { controller.ack(eventIds); null }
  }
}
